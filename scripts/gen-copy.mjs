#!/usr/bin/env node
// Generates apps/anneal/content/copy.deck.ts from docs/copy-deck-v3.md, so
// every key reaches the code word for word. Run after the deck changes:
//   node scripts/gen-copy.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const md = readFileSync(`${root}docs/copy-deck-v3.md`, 'utf8');
const block = /```\n([\s\S]*?)```/.exec(md)?.[1];
if (!block) throw new Error('No copy block found in the deck.');

const entries = [];
for (const line of block.split('\n')) {
  const m = /^([a-zA-Z0-9.]+): (.*)$/.exec(line);
  if (m) entries.push([m[1], m[2]]);
}

const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
const out = `// Generated by scripts/gen-copy.mjs from docs/copy-deck-v3.md. Do not edit.
export const deck = {
${body}
} as const;
`;
writeFileSync(`${root}apps/anneal/content/copy.deck.ts`, out);
console.log(`gen-copy: wrote ${entries.length} keys.`);
